// Plan g-nasadit-prirodu (owner, 8 Nov 2026: "udělej revizi asetů k nasazení do hry"): packs the approved Studio
// nature exports that have a game counterpart (stone and iron deposits, rock obstacles, shrubs, the orchard tree and
// the wheat field tile) into ONE atlas, public/assets/nature/nature-atlas.v2.png, and writes src/data/natureArt.js
// with each frame's rectangle, its art source and the origin from the metadata. One file instead of ~70 keeps the
// game page under the 512-file cap of a published page. Only variants with status `approved` in art/approvals.json
// are packed; the pixels are copied unchanged (tests/nature-art.test.js checks them against the exports).
// Re-run after a Studio revision: node scripts/export-nature-art.mjs
import { readFile, writeFile, mkdir, readdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodePng, encodePng } from './png-lite.mjs';

const root=fileURLToPath(new URL('../',import.meta.url));
const approvals=JSON.parse(await readFile(path.join(root,'art/approvals.json'),'utf8')).assets;
// The Studio assets the game shows. velke-prirodni-objekty added the large (3 × 3) deposits, the 2 × 2 rock obstacles,
// the rock ridge (4 × 2) and the thickets (2 × 1, 2 × 2, 3 × 2), which now have game objects of their size.
const NATURE_ASSETS=['stone-deposit-medium','stone-deposit-small','iron-deposit-medium','iron-deposit-small',
  'rock-obstacles-small','shrubs','shrubs-seasons','orchard-tree','wheat-field-tile',
  'stone-deposit-large','iron-deposit-large','rock-obstacles-medium','rock-ridge','thicket-2x1','thicket-2x2','thicket-3x2'];
const round=v=>Math.round(v*1e5)/1e5;
const images=[],skipped=[];
for(const asset of NATURE_ASSETS){
  for(const [variant,record] of Object.entries(approvals[asset]?.variants??{})){
    if(record.status!=='approved'){skipped.push(`${asset}/${variant}: ${record.status}`);continue;}
    const base=`art/sprites/${asset}/${variant}.v${record.version}`;
    const meta=JSON.parse(await readFile(path.join(root,`${base}.json`),'utf8'));
    const png=decodePng(await readFile(path.join(root,`${base}.png`)));
    images.push({asset,variant,artSource:`${base}.json`,origin:{x:round(meta.origin.x),y:round(meta.origin.y)},png});
  }
}
// Shelf packing, tallest first, one transparent pixel between frames (no bleeding when scaled).
const WIDTH=1024,GAP=1;images.sort((a,b)=>b.png.height-a.png.height||b.png.width-a.png.width||a.variant.localeCompare(b.variant));
let x=0,y=0,shelf=0;
for(const image of images){
  if(x+image.png.width>WIDTH){x=0;y+=shelf+GAP;shelf=0;}
  image.rect={x,y,w:image.png.width,h:image.png.height};x+=image.png.width+GAP;shelf=Math.max(shelf,image.png.height);
}
const HEIGHT=y+shelf,atlas=new Uint8Array(WIDTH*HEIGHT*4);
for(const {png,rect} of images)for(let row=0;row<rect.h;row++)atlas.set(png.data.subarray(row*rect.w*4,(row+1)*rect.w*4),((rect.y+row)*WIDTH+rect.x)*4);
// The file name carries the atlas version (v2: velke-prirodni-objekty), so a cached older atlas with other frame
// rectangles is never used; older atlas files are removed (the page holds one atlas file).
const ATLAS='nature-atlas.v2.png';
await mkdir(path.join(root,'public/assets/nature'),{recursive:true});
for(const file of await readdir(path.join(root,'public/assets/nature')))if(/^nature-atlas\.v\d+\.png$/.test(file)&&file!==ATLAS)await rm(path.join(root,'public/assets/nature',file));
await writeFile(path.join(root,`public/assets/nature/${ATLAS}`),encodePng({width:WIDTH,height:HEIGHT,data:atlas}));
const frames=Object.fromEntries(images.sort((a,b)=>a.variant.localeCompare(b.variant)).map(i=>[i.variant,{...i.rect,origin:i.origin,artSource:i.artSource}]));
await writeFile(path.join(root,'src/data/natureArt.js'),
`// Generated by scripts/export-nature-art.mjs from art/approvals.json (plan g-nasadit-prirodu). Do not edit: re-run
// the script after a Studio revision. Each frame is a byte-for-byte copy of an approved export packed into one atlas;
// origins come from its metadata (the studio anchor: the centre of the object's footprint).
export const NATURE_ATLAS=Object.freeze({src:'/assets/nature/${ATLAS}',width:${WIDTH},height:${HEIGHT},frames:Object.freeze(${JSON.stringify(frames)})});
`);
console.log(JSON.stringify({packed:images.length,atlas:`${WIDTH}x${HEIGHT}`,skipped},null,1));
