// Plan m-zvirata-nahodny-vzhled: copies the approved animal looks (art/approvals.json) into public/assets and writes
// src/data/objects/approvedAnimalArt.js. A look is a variant with a walk sheet; a variant named <look>-<pose> without
// one is a pose of that look (sit, run, attack, wounded, pounce). Re-run after a Studio revision of animals.
import { readFile, writeFile, mkdir, copyFile, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root=fileURLToPath(new URL('../',import.meta.url));
const SPECIES=['cat','dog','wolf','rat'];
// Young animals use their own look instead of a random adult one.
const YOUNG={cat:'cat-kitten'};
const exists=file=>access(file).then(()=>true,()=>false);
const approvals=JSON.parse(await readFile(path.join(root,'art/approvals.json'),'utf8')).assets;
const out={},target=path.join(root,'public/assets/characters/animals');await mkdir(target,{recursive:true});
const round=o=>o&&{x:Math.round(o.x*1e5)/1e5,y:Math.round(o.y*1e5)/1e5};
for(const species of SPECIES){
  const entry=approvals[species];if(!entry)continue;
  const approved=Object.entries(entry.variants).filter(([,v])=>v.status==='approved').map(([id,v])=>({id,version:v.version}));
  const looks=[],poses={};
  for(const {id,version} of approved){
    const base=`${id}.v${version}`,dir=path.join(root,'art/sprites',species),meta=JSON.parse(await readFile(path.join(dir,`${base}.json`),'utf8'));
    if(meta.walk&&await exists(path.join(dir,`${base}.walk.png`))){
      await copyFile(path.join(dir,`${base}.walk.png`),path.join(target,`${base}.walk.png`));
      looks.push({id,base:`/assets/characters/animals/${base}`,artSource:`art/sprites/${species}/${base}.json`,walk:{frameWidth:meta.walk.frameWidth,frameHeight:meta.walk.frameHeight,origin:round(meta.walk.origin),fps:meta.walk.fps??6},poses:{}});
    }else poses[id]={version,base,meta};
  }
  for(const [id,{base,meta}] of Object.entries(poses)){
    const look=looks.filter(l=>id.startsWith(`${l.id}-`)).sort((a,b)=>b.id.length-a.id.length)[0];if(!look)continue;
    await copyFile(path.join(root,'art/sprites',species,`${base}.png`),path.join(target,`${base}.png`));
    look.poses[id.slice(look.id.length+1)]={src:`/assets/characters/animals/${base}.png`,origin:round(meta.origin)};
  }
  const young=YOUNG[species]??null;
  out[species]={preferred:entry.preferred,young:looks.some(l=>l.id===young)?young:null,looks:Object.fromEntries(looks.map(l=>[l.id,{base:l.base,artSource:l.artSource,walk:l.walk,poses:l.poses}]))};
}
const text=`// Generated by scripts/export-animal-art.mjs from art/approvals.json (plan m-zvirata-nahodny-vzhled). Do not edit:
// re-run the script after a Studio revision. Each look has a walk sheet (8 rows = facings, 3 columns idle/stride-a/
// stride-b, origin at the ground point) and optional single-image poses facing the viewer's right.
export const APPROVED_ANIMAL_ART=Object.freeze(${JSON.stringify(out,null,1)});
`;
await writeFile(path.join(root,'src/data/objects/approvedAnimalArt.js'),text);
for(const [species,s] of Object.entries(out))console.log(`${species}: ${Object.keys(s.looks).join(', ')}${s.young?` (young ${s.young})`:''}; poses ${Object.entries(s.looks).flatMap(([id,l])=>Object.keys(l.poses).map(p=>`${id}-${p}`)).join(', ')||'none'}`);
