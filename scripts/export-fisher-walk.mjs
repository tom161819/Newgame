// The approved Fisher looks (art/sprites/fisher, status `approved`) had no game counterpart: Fishers walking to the
// storage were drawn with the old procedural figure, only the fishing loop at the water was the approved art.
// The walk sheets go into src/data/fisherWalkArt.js as data URLs, so the game page gets no new file (512-file cap of
// a published page). Re-run after a Studio revision: node scripts/export-fisher-walk.mjs
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const approvals=JSON.parse(await readFile(path.join(root,'art/approvals.json'),'utf8')).assets.fisher?.variants??{};
const round=o=>({x:Math.round(o.x*1e5)/1e5,y:Math.round(o.y*1e5)/1e5});
const looks={};
for(const [variant,record] of Object.entries(approvals)){
  if(record.status!=='approved')continue;
  const base=`art/sprites/fisher/${variant}.v${record.version}`,meta=JSON.parse(await readFile(path.join(root,`${base}.json`),'utf8')),w=meta.walk;
  const png=await readFile(path.join(root,`${base}.walk.png`));
  looks[variant]={artSource:`${base}.json`,walkSrc:`data:image/png;base64,${png.toString('base64')}`,walk:{frameWidth:w.frameWidth,frameHeight:w.frameHeight,origin:round(w.origin),fps:w.fps??6}};
}
await writeFile(path.join(root,'src/data/fisherWalkArt.js'),
`// Generated by scripts/export-fisher-walk.mjs from the approved Fisher looks. Do not edit: re-run the script.
// Walk sheets as data URLs (8 rows = facing 0–7, 3 columns idle / stride-a / stride-b, like the villager walk sheets).
export const FISHER_WALK_ART=Object.freeze(${JSON.stringify(looks)});
export const FISHER_LOOKS=Object.freeze({male:${JSON.stringify(looks['fisher-male']?'fisher-male':null)},female:${JSON.stringify(looks['fisher-female']?'fisher-female':null)}});
`);
console.log(Object.keys(looks));
