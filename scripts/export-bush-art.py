"""Owner's Blender bushes and thickets (Medieval_Kingdom_Kere_a_houstiny, 18 Nov 2026: "keře jsou zde"; approved in the
Studio as the *-views variants). 28 models x 4 seasons x 4 views from art/sprites/bush-renders/<model>/<season>-<angle>.png
(the pack's 1x game renders, one tile 64 px wide) are packed into ONE atlas, public/assets/nature/bush-atlas.v1.png,
and src/data/bushArt.js lists each frame <model>-<season>-<angle> with its rectangle and its origin (sprite.json
origin_px: the centre of the footprint on the ground). One file keeps the page under its 512-file cap.
Re-run: python3 scripts/export-bush-art.py
"""
import json, os
from PIL import Image
root = os.path.join(os.path.dirname(__file__), '..')
src = os.path.join(root, 'art/sprites/bush-renders')
images = []
for model in sorted(os.listdir(src)):
  d = os.path.join(src, model)
  if not os.path.isdir(d): continue
  meta = json.load(open(os.path.join(d, 'sprite.json')))
  for season in ('spring', 'summer', 'autumn', 'winter'):
    for angle in ('000', '090', '180', '270'):
      im = Image.open(os.path.join(d, f'{season}-{angle}.png')).convert('RGBA'); v = meta['views'][str(int(angle))]
      assert list(im.size) == v['size_px'], (model, season, angle)
      images.append({'name': f'{model}-{season}-{angle}', 'im': im, 'origin': {'x': round(v['origin_px'][0] / im.width, 5), 'y': round(v['origin_px'][1] / im.height, 5)}})
WIDTH, GAP = 2048, 1
images.sort(key=lambda i: (-i['im'].height, -i['im'].width, i['name']))
x = y = shelf = 0
for i in images:
  w, h = i['im'].size
  if x + w > WIDTH: x = 0; y += shelf + GAP; shelf = 0
  i['rect'] = {'x': x, 'y': y, 'w': w, 'h': h}; x += w + GAP; shelf = max(shelf, h)
HEIGHT = y + shelf
atlas = Image.new('RGBA', (WIDTH, HEIGHT), (0, 0, 0, 0))
for i in images: atlas.paste(i['im'], (i['rect']['x'], i['rect']['y']))
ATLAS = 'bush-atlas.v1.png'
os.makedirs(os.path.join(root, 'public/assets/nature'), exist_ok=True)
atlas.save(os.path.join(root, 'public/assets/nature', ATLAS), optimize=True)
frames = {i['name']: {**i['rect'], 'origin': i['origin']} for i in sorted(images, key=lambda i: i['name'])}
open(os.path.join(root, 'src/data/bushArt.js'), 'w').write(
  "// Generated by scripts/export-bush-art.py from the owner's Blender bushes and thickets (art/sprites/bush-renders,\n"
  "// 18 Nov 2026). Do not edit: re-run the script. Frame <model>-<season>-<angle>; origin = footprint centre on the ground.\n"
  f"export const BUSH_ATLAS=Object.freeze({{src:'/assets/nature/{ATLAS}',width:{WIDTH},height:{HEIGHT},frames:Object.freeze({json.dumps(frames, separators=(',', ':'))})}});\n")
print(len(images), WIDTH, HEIGHT, os.path.getsize(os.path.join(root, 'public/assets/nature', ATLAS)))
