// Copies the Studio icon sets chosen for Kingdom Policy (tax coin stacks, ration bowls) into src/ui/policyIconsArt.js as
// inline SVG strings, so the sliders need no extra request and work in the artifact build. Run after a new revision:
// node scripts/sync-policy-icons.mjs
import { readFileSync,writeFileSync } from 'node:fs';
export const POLICY_ICON_SETS={
  tax:{variant:'art/sprites/tax-icons/tax-icons-stacks.v1',levels:{none:'none',low:'low',normal:'normal',high:'high',very_high:'very-high'}},
  rations:{variant:'art/sprites/ration-icons/ration-icons-bowls.v1',levels:{small:'small',normal:'normal',generous:'generous'}},
};
export function policyIconsModule(root='.'){
  const out={};for(const [kind,{variant,levels}] of Object.entries(POLICY_ICON_SETS)){out[kind]={};for(const [level,file] of Object.entries(levels))out[kind][level]=readFileSync(`${root}/${variant}.${file}.svg`,'utf8').trim();}
  return `// Generated by scripts/sync-policy-icons.mjs from the Studio sets chosen on 7 Nov (do not edit by hand):\n// ${POLICY_ICON_SETS.tax.variant}.<level>.svg and ${POLICY_ICON_SETS.rations.variant}.<level>.svg\nexport const POLICY_ICON_ART=Object.freeze(${JSON.stringify(out,null,1)});\n`;
}
if(import.meta.url===`file://${process.argv[1]}`){writeFileSync('src/ui/policyIconsArt.js',policyIconsModule());console.log('src/ui/policyIconsArt.js written');}
