#!/usr/bin/env node
// Owner 21 Nov 2026 ("rozděl to studio na 2, laby přidej tam kde bude víc místa"): a claude.ai page holds at most 512
// files, so the Asset Studio is built as two pages. This writes studio/src/parts/{all,buildings,world}.js – the
// build-time file lists (import.meta.glob needs literal patterns) for each part:
//   buildings – art/assets/buildings/*, their exports and the game's building sprites; Fire Lab, Phaser demo,
//               Buildings in game.
//   world     – every other category (units, trees, nature, decorations, terrain, equipment, ui) and the other game
//               sprites; UI Lab, World Lab, Path Lab, Light Lab.
//   all       – everything (npm run studio and the smoke test).
import { readdirSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const categories = readdirSync(path.join(root, 'art/assets')).filter(c => !c.startsWith('.'));
const assetsOf = c => readdirSync(path.join(root, 'art/assets', c)).filter(a => existsSync(path.join(root, 'art/assets', c, a, 'asset.json')));
const buildingAssets = new Set(assetsOf('buildings'));
const spriteDirs = readdirSync(path.join(root, 'art/sprites')).filter(d => !d.startsWith('.'));
const publicDirs = readdirSync(path.join(root, 'public/assets')).filter(d => !d.startsWith('.'));
// Superseded exports left out of every part (they stay in the repo).
const EXCLUDE = ['{oak-tree,pine-tree}/*-season-*.x2.png', '{watchtower,gate}/*-tripo*.v1*.png', 'wall-kit-preview/wall-kit-preview-diagonal{,-across}.v[1-4].png'];
const brace = list => list.length === 1 ? list[0] : `{${list.join(',')}}`;

function part(name, cats, sprites, publics) {
  const P = '../../../';
  const pngs = [`${P}art/sprites/${brace(sprites)}/*.png`, ...EXCLUDE.map(e => `!${P}art/sprites/${e}`)];
  return `// Generated by scripts/studio-parts.mjs (part "${name}") – do not edit; run npm run studio:parts.
const specs = import.meta.glob('${P}art/assets/${brace(cats)}/*/asset.json', { eager: true, import: 'default' });
const game = import.meta.glob('${P}public/assets/${brace(publics)}/**/*.{png,svg,webp}', { eager: true, query: '?url', import: 'default' });
const pngs = import.meta.glob(${JSON.stringify(pngs).replace(/"/g, "'")}, { eager: true, query: '?url', import: 'default' });
const metas = import.meta.glob('${P}art/sprites/${brace(sprites)}/*.json', { eager: true, import: 'default' });
const strip = modules => Object.fromEntries(Object.entries(modules).map(([key, value]) => [key.replace('${P}', ''), value]));
export const STUDIO_PART = '${name}';
// Keys: 'art/assets/…/asset.json', 'public/assets/…', 'art/sprites/…'.
export const specModules = strip(specs), gameSpriteModules = strip(game), exportedPngModules = strip(pngs), exportedMetaModules = strip(metas);
`;
}
const out = path.join(root, 'studio/src/parts');
mkdirSync(out, { recursive: true });
const worldCats = categories.filter(c => c !== 'buildings');
writeFileSync(path.join(out, 'all.js'), part('all', categories, spriteDirs, publicDirs));
writeFileSync(path.join(out, 'buildings.js'), part('buildings', ['buildings'], spriteDirs.filter(d => buildingAssets.has(d)), ['buildings', 'resources']));
writeFileSync(path.join(out, 'world.js'), part('world', worldCats, spriteDirs.filter(d => !buildingAssets.has(d)), publicDirs.filter(d => d !== 'buildings')));
console.log(`studio parts: buildings ${[...buildingAssets].length} assets, world ${worldCats.join('/')} (${spriteDirs.filter(d => !buildingAssets.has(d)).length} sprite folders)`);
