"""Packs the frames of scripts/blender/render-soldier.py into the game's soldier sheets.

python3 pack-soldier-sheets.py <render root> <enemy render root or -> <public villagers dir> <src/data/soldierAnimArt.js>
Each model folder holds <k>-<col>.png at 3x. Owner 17 Nov 2026 ("the models are blurred"): the sheets keep 2x detail
and the game draws them at half size (walk.scale 0.5), so zooming in stays sharp. All frames of a model are cropped
to one box (the feet stay on the same pixel) and laid out frame after frame, 12 to a row (sheet under 4096 px):
frame index = facing * columns + column, facings in FACING_INDEX order; columns idle, walk 0-7, attack 0-5, die 0-3,
idle 1-5. The enemy root holds the same models rendered in the enemy army's colour (--hue 0.15, steel blue).
"""
import sys, os, json, math
from PIL import Image

root, enemy_root, outdir, datafile = sys.argv[1:5]
OUT, PER_ROW = 2, 12
# (render folder, our unit, look name, enemy unit or None). Owner 18 Nov 2026 (Medieval_Kingdom_Vojaci_5_trid_3D): the
# Soldier gets his own figure (05_Vojak); the Branec now dresses the untrained Recruits (unit key 'recruit'); the
# enemy soldier keeps the Branec. Folders missing from a root are skipped (the enemy root has the first four only).
MODELS = [('01_Rytir', 'knight', 'knight', 'knight'), ('02_Lucistnik', 'archer', 'archer', 'archer'), ('03_Sermir', 'swordsman', 'swordsman', 'swordsman'),
          ('04_Branec', 'recruit', 'recruit', 'soldier'), ('05_Vojak', 'soldier', 'soldier', None), ('06_Kusnik', 'crossbowman', 'crossbowman', None),
          ('07_Halapartnik', 'halberdier', 'halberdier', None), ('08_Kralovsky_lucistnik', 'royal_archer', 'royal-archer', None),
          ('09_Lehky_jezdec', 'light_cavalry', 'light-cavalry', None)]
entries = {}

def pack(d, look):
  layout = json.load(open(os.path.join(d, 'layout.json')))
  fw, fh = layout['frameWidth'] * OUT, layout['frameHeight'] * OUT; cols = len(layout['columns'])
  frames = {}
  for k in range(8):
    for c in range(cols):
      im = Image.open(os.path.join(d, f'{k}-{c:02d}.png')).convert('RGBA').resize((fw, fh), Image.LANCZOS)
      a = im.getchannel('A').point(lambda v: 0 if v < 10 else v); im.putalpha(a); frames[k, c] = im
  box = None
  for im in frames.values():
    b = im.getbbox()
    if b: box = b if not box else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
  x0, y0, x1, y1 = max(0, box[0] - 2), max(0, box[1] - 2), min(fw, box[2] + 2), min(fh, box[3] + 2)
  w, h = x1 - x0, y1 - y0; total = 8 * cols; rows = math.ceil(total / PER_ROW)
  sheet = Image.new('RGBA', (w * PER_ROW, h * rows), (0, 0, 0, 0))
  for (k, c), im in frames.items():
    n = k * cols + c; sheet.paste(im.crop((x0, y0, x1, y1)), ((n % PER_ROW) * w, (n // PER_ROW) * h))
  path = os.path.join(outdir, f'{look}.v2.walk.png'); sheet.save(path, optimize=True)
  ax, ay = layout['anchor'][0] * OUT, layout['anchor'][1] * OUT
  names = layout['columns']; idx = lambda kind: [i for i, n in enumerate(names) if n.startswith(kind + '-')]
  print(look, w, h, sheet.size, os.path.getsize(path))
  return {'frameWidth': w, 'frameHeight': h, 'origin': {'x': round((ax - x0) / w, 5), 'y': round((ay - y0) / h, 5)}, 'columns': cols,
          'perRow': PER_ROW, 'walk': idx('walk'), 'attack': idx('attack'), 'die': idx('die'), 'idles': idx('idle')}

for folder, unit, name, enemy in MODELS:
  look = f'army-{name}'; entries[look] = {**pack(os.path.join(root, folder), look), 'unit': unit, 'model': folder, 'side': 'ours'}
  if enemy and enemy_root != '-' and os.path.isdir(os.path.join(enemy_root, folder)):
    look = f'enemy-{name}'; entries[look] = {**pack(os.path.join(enemy_root, folder), look), 'unit': enemy, 'model': folder, 'side': 'enemy'}

lines = ['// Generated by scripts/blender/pack-soldier-sheets.py from the owner\'s rigged soldier models (Medieval_Kingdom_Vojaci_3D,',
         '// 16 Nov 2026: "nasaď je rovnou do hry a vytvoř animace"; Medieval_Kingdom_Vojaci_5_trid_3D, 18 Nov 2026).',
         '// Do not edit by hand; re-render and re-pack instead. The Light Cavalry figure includes his horse.',
         '// Frame = facing * columns + column (FACING_INDEX); columns idle, walk 0-7, attack 0-5, die 0-3, idle 1-5.',
         '// Drawn at walk.scale 0.5: the sheets hold double detail for zooming in (owner 17 Nov 2026).',
         'export const SOLDIER_ANIM_ART=Object.freeze({']
for look, e in entries.items():
  lines.append(f"  '{look}':{{base:'/assets/characters/villagers/{look}.v2',model:'{e['model']}',side:'{e['side']}',walk:{{frameWidth:{e['frameWidth']},frameHeight:{e['frameHeight']},origin:{json.dumps(e['origin'])},fps:10,scale:{1/OUT}}},"
               f"anim:{{columns:{e['columns']},perRow:{e['perRow']},idle:0,idles:{json.dumps(e['idles'])},walk:{json.dumps(e['walk'])},attack:{json.dumps(e['attack'])},die:{json.dumps(e['die'])},attackFps:10,dieFps:8}}}},")
lines.append('});')
lines.append('export const SOLDIER_ANIM_LOOKS=Object.freeze({' + ','.join(f"{e['unit']}:'{look}'" for look, e in entries.items() if e['side'] == 'ours') + '});')
lines.append('export const ENEMY_ANIM_LOOKS=Object.freeze({' + ','.join(f"{e['unit']}:'{look}'" for look, e in entries.items() if e['side'] == 'enemy') + '});')
open(datafile, 'w').write('\n'.join(lines) + '\n')
