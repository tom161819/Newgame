"""Packs the frames of scripts/blender/render-soldier.py into the game's soldier sheets.

python3 pack-soldier-sheets.py <render root> <public villagers dir> <src/data/soldierAnimArt.js>
Each model folder holds <k>-<col>.png at 3x; the frames are reduced to 1x, cropped to one box shared by all frames
of the model (so the feet stay on the same pixel) and laid out 8 rows (facings) x columns (idle, walk, attack, die).
"""
import sys, os, json
from PIL import Image

root, outdir, datafile = sys.argv[1:4]
MODELS = [('01_Rytir', 'army-knight', 'knight'), ('02_Lucistnik', 'army-archer', 'archer'),
          ('03_Sermir', 'army-swordsman', 'swordsman'), ('04_Branec', 'army-recruit', 'soldier')]
entries = {}
for folder, look, unit in MODELS:
  d = os.path.join(root, folder); layout = json.load(open(os.path.join(d, 'layout.json')))
  fw, fh, ss = layout['frameWidth'], layout['frameHeight'], layout['supersample']; cols = len(layout['columns'])
  frames = {}
  for k in range(8):
    for c in range(cols):
      im = Image.open(os.path.join(d, f'{k}-{c:02d}.png')).convert('RGBA').resize((fw, fh), Image.LANCZOS)
      a = im.getchannel('A').point(lambda v: 0 if v < 10 else v); im.putalpha(a); frames[k, c] = im
  box = None
  for im in frames.values():
    b = im.getbbox()
    if b: box = b if not box else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
  x0, y0, x1, y1 = max(0, box[0] - 1), max(0, box[1] - 1), min(fw, box[2] + 1), min(fh, box[3] + 1)
  w, h = x1 - x0, y1 - y0
  sheet = Image.new('RGBA', (w * cols, h * 8), (0, 0, 0, 0))
  for (k, c), im in frames.items(): sheet.paste(im.crop((x0, y0, x1, y1)), (c * w, k * h))
  sheet.save(os.path.join(outdir, f'{look}.v1.walk.png'), optimize=True)
  ax, ay = layout['anchor']
  names = layout['columns']; idx = lambda kind: [i for i, n in enumerate(names) if n.startswith(kind + '-')]
  entries[look] = {'unit': unit, 'model': folder, 'frameWidth': w, 'frameHeight': h,
                   'origin': {'x': round((ax - x0) / w, 5), 'y': round((ay - y0) / h, 5)}, 'columns': cols,
                   'walk': idx('walk'), 'attack': idx('attack'), 'die': idx('die'), 'idles': idx('idle')}
  print(look, w, h, sheet.size, os.path.getsize(os.path.join(outdir, f'{look}.v1.walk.png')))

lines = ['// Generated by scripts/blender/pack-soldier-sheets.py from the owner\'s rigged soldier models (Medieval_Kingdom_Vojaci_3D,',
         '// 16 Nov 2026: "nasaď je rovnou do hry a vytvoř animace"). Do not edit by hand; re-render and re-pack instead.',
         '// Sheet: 8 rows in FACING_INDEX order; columns idle, walk 0-7, attack 0-5, die 0-3.',
         'export const SOLDIER_ANIM_ART=Object.freeze({']
for look, e in entries.items():
  lines.append(f"  '{look}':{{base:'/assets/characters/villagers/{look}.v1',model:'{e['model']}',walk:{{frameWidth:{e['frameWidth']},frameHeight:{e['frameHeight']},origin:{json.dumps(e['origin'])},fps:10}},"
               f"anim:{{columns:{e['columns']},idle:0,idles:{json.dumps(e['idles'])},walk:{json.dumps(e['walk'])},attack:{json.dumps(e['attack'])},die:{json.dumps(e['die'])},attackFps:10,dieFps:8}}}},")
lines.append('});')
lines.append('export const SOLDIER_ANIM_LOOKS=Object.freeze({' + ','.join(f"{e['unit']}:'{look}'" for look, e in entries.items()) + '});')
open(datafile, 'w').write('\n'.join(lines) + '\n')
